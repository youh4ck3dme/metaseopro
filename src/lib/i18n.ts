export function isLocale(value: string | undefined): value is Locale {
  return value === "sk" || value === "en" || value === "de";
}

export function readLocaleCookie(): Locale | null {
  if (typeof document === "undefined") return null;
  const match = document.cookie.match(/(?:^|; )locale=(sk|en|de)(?:;|$)/);
  return match && isLocale(match[1]) ? match[1] : null;
}

export function writeLocaleCookie(locale: Locale) {
  if (typeof document === "undefined") return;
  document.cookie = `locale=${locale}; path=/; max-age=31536000; samesite=lax`;
}

export function localeFromNavigator(): Locale {
  if (typeof navigator === "undefined") return "sk";
  const lang = navigator.language.toLowerCase();
  if (lang.startsWith("en")) return "en";
  if (lang.startsWith("de")) return "de";
  return "sk";
}

export function pageUrl(locale: Locale, path: string) {
  const clean = path.replace(/^\/(sk|en|de)(?=\/|$)/, "") || "/";
  return `${SITE}/${locale}${clean === "/" ? "" : clean}`;
}

export function swapLocale(pathname: string, next: Locale) {
  if (/^\/(sk|en|de)(?=\/|$)/.test(pathname)) {
    return pathname.replace(/^\/(sk|en|de)/, `/${next}`);
  }
  return `/${next}${pathname === "/" ? "" : pathname}`;
}

